const SOLID_ICONS = new Set(['facebook', 'x', 'instagram', 'tiktok', 'linkedin', 'youtube']);

export default function Icon({ name, size = 20, strokeWidth = 1.7, className = '', ...rest }) {
  const content = paths[name] ?? paths.sparkles;
  const solid = SOLID_ICONS.has(name);
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill={solid ? 'currentColor' : 'none'}
      stroke={solid ? 'none' : 'currentColor'}
      strokeWidth={solid ? undefined : strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={`icon ${className}`}
      aria-hidden="true"
      focusable="false"
      {...rest}
    >
      {content}
    </svg>
  );
}
